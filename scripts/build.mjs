import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { bundledLicenses } from './licenses.mjs';
import { PLUGIN_NAME, VERSION } from '../shared/identity.js';
const root = new URL('../', import.meta.url);
const pkg = JSON.parse(await readFile(new URL('package.json', root), 'utf8'));
if (pkg.name !== PLUGIN_NAME || pkg.version !== VERSION) throw new Error('Package and protocol identity differ');
const result = await build({
  absWorkingDir: root.pathname,
  entryPoints: ['client/index.js'], bundle: true, write: false,
  platform: 'browser', format: 'cjs', target: 'chrome100', metafile: true,
  external: ['react', 'react-dom', 'react-dom/client'],
  // Delegate JSX to the React instance supplied by DSH, including React 18.
  alias: {
    'react/jsx-runtime': new URL('client/jsx-runtime.js', root).pathname,
    'react/jsx-dev-runtime': new URL('client/jsx-runtime.js', root).pathname,
  },
  define: { 'process.env.NODE_ENV': '"production"' },
  charset: 'utf8', legalComments: 'inline', logLevel: 'warning',
});
const output = `// Generated by scripts/build.mjs; do not edit.\nwindow.__ModuleLoader__.load({\n  id: '${PLUGIN_NAME}',\n  factory(require) {\n    const module = { exports: {} };\n    const exports = module.exports;\n${result.outputFiles[0].text}\n    return module.exports;\n  }\n});\n`;
const file = new URL('lib/client.js', root);
const notices = new URL('THIRD_PARTY_NOTICES.md', root);
const licenses = await bundledLicenses(root, result.metafile.inputs);
if (process.argv.includes('--check')) {
  if (await readFile(file, 'utf8') !== output) throw new Error('Client bundle is stale; run npm run build');
  if (await readFile(notices, 'utf8') !== licenses) throw new Error('Third-party notices are stale');
  console.log('Client bundle and third-party notices match source');
} else {
  await mkdir(new URL('lib/', root), { recursive: true });
  await writeFile(file, output);
  await writeFile(notices, licenses);
  console.log(`Built ${PLUGIN_NAME} ${VERSION}`);
}
